"""London relocation areas dataset — canonical source of truth."""


def _commute_band(mins):
    if mins <= 20: return "≤20 min"
    if mins <= 30: return "21–30 min"
    if mins <= 40: return "31–40 min"
    if mins <= 50: return "41–50 min"
    return "51+ min"


def _rent_band(rent):
    if rent < 2000: return "Under £2,000"
    if rent < 2400: return "£2,000–£2,400"
    if rent <= 2800: return "£2,400–£2,800"
    return "Over £2,800"


def _owner_band(pct):
    if pct > 60: return "High (>60%)"
    if pct >= 30: return "Med (30–60%)"
    return "Low (<30%)"


def _social_band(pct):
    if pct <= 15: return "Low"
    if pct <= 30: return "Med"
    return "High"


def _score_tier(score):
    if score >= 80: return "Top pick (80+)"
    if score >= 65: return "Strong contender (65–79)"
    if score >= 50: return "Compromise (50–64)"
    return "Weak fit (<50)"


def compute_score(a, weights=None):
    if weights is None:
        weights = {"commute": 0.35, "garden": 0.20, "bike": 0.15, "space": 0.15, "rent": 0.15}
    total_w = sum(weights.values())
    w = {k: v / total_w for k, v in weights.items()}

    base = 50 if a["both_u30"] else 0
    her_pts = max(0, 25 - max(0, a["her_kx_mins"] - 20) * 2.5)
    him_pts = max(0, 25 - max(0, a["him_city_mins"] - 20) * 2.5)
    # Her commute weighted 60%, his 40%
    time_pts = her_pts * 0.60 + him_pts * 0.40
    change_pen = (a["her_changes"] + a["him_changes"]) * 5
    res_bonus = {"High": 10, "Med": 5, "Low": 0}[a["line_resilience"]]
    commute_raw = max(0, min(100, base + time_pts - change_pen + res_bonus))
    commute_score = commute_raw / 100.0

    garden_score = 1.0 if a["period_garden_flat_u2800"] else 0.0
    bike_score = {"Good": 1.0, "OK": 0.5, "Hard": 0.0}[a["bike_storage"]]
    space_score = 1.0 if a["three_bed_u2800"] else 0.0
    rent_score = max(0, min(1, (2800 - a["indicative_rent"]) / 1200))

    variable_pts = 82 * (
        w["commute"] * commute_score +
        w["garden"] * garden_score +
        w["bike"] * bike_score +
        w["space"] * space_score +
        w["rent"] * rent_score
    )

    bonus = 0
    bonus += 3 if a["crime_rate_band"] == "Low" else (1 if a["crime_rate_band"] == "Med" else 0)
    bonus += 2 if a["drug_crime_band"] == "Low" else 0
    bonus += 2 if a["social_housing"] == "Low" else 0
    bonus += 2 if a["big_park"] else 0
    bonus += 2 if a["gym_access"] >= 4 else 0
    bonus += 2 if a["strike_resilience"] == "Good" else 0
    bonus += 1 if a["flood_risk"] == "Low" else 0
    bonus += 1 if a["heathrow_noise"] == "None" else 0
    bonus += 1 if a["night_tube"] else 0
    bonus += 1 if a["cycling"] >= 4 else 0
    bonus = min(18, bonus)

    return round(min(100, max(0, variable_pts + bonus)), 1)


def _build(raw):
    a = raw.copy()
    a["both_u30"] = a["her_kx_mins"] <= 30 and a["him_city_mins"] <= 30
    a["her_commute_band"] = _commute_band(a["her_kx_mins"])
    a["him_commute_band"] = _commute_band(a["him_city_mins"])
    a["rent_band"] = _rent_band(a["indicative_rent"])
    a["owner_occupier_band"] = _owner_band(a["owner_occupier_pct"])
    a["social_housing"] = _social_band(a["community_housing_pct"])
    a["two_plus_grocers"] = a["quality_grocers_count"] >= 2
    a["score"] = compute_score(a)
    a["score_tier"] = _score_tier(a["score"])
    if a["area"] == "East Putney/Southfields":
        a["status"] = "Benchmark"
    elif a["both_u30"] and a["score"] >= 65:
        a["status"] = "Contender"
    else:
        a["status"] = "Compromise"
    return a


